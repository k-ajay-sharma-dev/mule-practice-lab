// Palette of Mule 4 building blocks for the Flow Designer (design only, never executed).
//
// kind decides where a component may be placed and what it contains:
//   source    – the single trigger at the top of a flow
//   processor – a plain step
//   scope     – a step that wraps its own list of steps
//   router    – a step with several routes, each holding steps
//   handler   – an error handler (On Error Propagate / Continue), holds steps
//
// Field types: text | expression | number | select | textarea


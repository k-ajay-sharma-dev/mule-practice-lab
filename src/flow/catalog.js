const MIME_TYPES = ['(auto)', 'application/json', 'application/xml', 'application/csv', 'text/plain', 'application/flatfile']
// Which database the Database Config connects to (decides the connection element in the exported XML)
export const DATABASES = ['Generic JDBC', 'Oracle', 'SQL Server', 'MySQL', 'PostgreSQL']
const dbField = () => select('database', 'Database', DATABASES)
const dbName = (c) => (c.database && c.database !== 'Generic JDBC' ? `[${c.database}] ` : '')

// File-style connectors (File, FTP, SFTP) share the same operations; prefix = XML namespace
function fileOps(prefix, name, base) {
  return {
    [`${prefix}-read`]: {
      label: `${name} Read`,
      group: 'files',
      kind: 'processor',
      glyph: '⇣',
      fields: [text('path', 'File path', `${base}/in/orders.csv`), select('outputMimeType', 'Output MIME type', MIME_TYPES)],
      summary: (c) => c.path,
    },
    [`${prefix}-list`]: {
      label: `${name} List`,
      group: 'files',
      kind: 'processor',
      glyph: '☰',
      fields: [text('directoryPath', 'Directory', `${base}/in`), text('matcher', 'File name pattern', '*.csv'), select('recursive', 'Recursive', ['false', 'true'])],
      summary: (c) => `${c.directoryPath}/${c.matcher || '*'}`,
    },
    [`${prefix}-delete`]: {
      label: `${name} Delete`,
      group: 'files',
      kind: 'processor',
      glyph: '✕',
      fields: [expr('path', 'Path', '#[attributes.path]')],
      summary: (c) => c.path,
    },
    [`${prefix}-rename`]: {
      label: `${name} Rename`,
      group: 'files',
      kind: 'processor',
      glyph: '✎',
      fields: [expr('path', 'Path', '#[attributes.path]'), text('to', 'New name', 'orders.csv.done')],
      summary: (c) => `→ ${c.to}`,
    },
    [`${prefix}-copy`]: {
      label: `${name} Copy`,
      group: 'files',
      kind: 'processor',
      glyph: '⧉',
      fields: [
        expr('sourcePath', 'Source path', '#[attributes.path]'),
        text('targetPath', 'Target directory', `${base}/backup`),
        select('overwrite', 'Overwrite', ['false', 'true']),
        text('renameTo', 'Rename to (optional)'),
      ],
      summary: (c) => `→ ${c.targetPath}`,
    },
    [`${prefix}-create-directory`]: {
      label: `${name} Create Directory`,
      group: 'files',
      kind: 'processor',
      glyph: '▣',
      fields: [text('directoryPath', 'Directory', `${base}/out/2026`)],
      summary: (c) => c.directoryPath,
    },
  }
}

// Salesforce Bulk API v2 operations that only need a job ID
function sfJobOp(type, label) {
  return {
    [type]: {
      label,
      group: 'enterprise',
      kind: 'processor',
      glyph: '☁',
      fields: [expr('jobId', 'Job ID', '#[vars.jobId]')],
      summary: (c) => c.jobId,
    },
  }
}

// One palette item per Workday web service; the Operation field picks the SOAP operation of that service
function workdayService(type, label, operation = '') {
  return {
    [type]: {
      label: `Workday ${label}`,
      group: 'enterprise',
      kind: 'processor',
      glyph: 'W',
      fields: [text('operation', 'Operation', operation), text('target', 'Target variable (optional)')],
      summary: (c) => `${c.operation}${c.target ? ` → vars.${c.target}` : ''}`,
    },
  }
}

